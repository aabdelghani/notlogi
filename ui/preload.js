const { contextBridge, ipcRenderer } = require('electron');
// the language the main process chose, with its translations
contextBridge.exposeInMainWorld('i18n', { load: () => ipcRenderer.sendSync('i18n') });

contextBridge.exposeInMainWorld('agent', {
  call: (method, params) => ipcRenderer.invoke('rpc', method, params || {}),
  connected: () => ipcRenderer.invoke('agent-connected'),
  onEvent: cb => ipcRenderer.on('agent-event', (_e, msg) => cb(msg)),
  onStatus: cb => ipcRenderer.on('agent-status', (_e, st) => cb(st)),
  saveJson: (name, data) => ipcRenderer.invoke('save-json', name, data),
  openJson: () => ipcRenderer.invoke('open-json'),
  openExternal: url => ipcRenderer.invoke('open-external', url),
  openPath: p => ipcRenderer.invoke('open-path', p),
  installUdev: () => ipcRenderer.invoke('install-udev'),
  briStatus: () => ipcRenderer.invoke('bri-status'),
  briSetup: () => ipcRenderer.invoke('bri-setup'),
  accessibility: prompt => ipcRenderer.invoke('accessibility', !!prompt),
  openAccessibility: () => ipcRenderer.invoke('open-accessibility'),
  inputMonitoringOpen: () => ipcRenderer.invoke('input-monitoring-open'),
  appIcon: spec => ipcRenderer.invoke('app-icon', spec),
  stopTool: name => ipcRenderer.invoke('stop-tool', name),
  windowAction: a => ipcRenderer.invoke('window-action', a),
  onWindowState: cb => ipcRenderer.on('window-state', (_e, s) => cb(s)),
  uiSettings: (patch) => ipcRenderer.invoke('ui-settings', patch || null),
  copy: text => ipcRenderer.invoke('copy-text', text),
  appInfo: () => ipcRenderer.invoke('app-info'),
  osdTest: kind => ipcRenderer.invoke('osd-test', kind),
  btPopTest: stage => ipcRenderer.invoke('btpop-test', stage),
  ringShow: () => ipcRenderer.invoke('ring-show'),
  diagReport: () => ipcRenderer.invoke('diag-report'),
  uninstallPlan: settings => ipcRenderer.invoke('uninstall-plan', !!settings),
  uninstall: settings => ipcRenderer.invoke('uninstall', !!settings),
  generalChanged: () => ipcRenderer.invoke('general-changed'),
  setTheme: t => ipcRenderer.invoke('set-theme', t),
  openBluetooth: () => ipcRenderer.invoke('open-bluetooth'),
  btOpen: () => ipcRenderer.invoke('bt-open'),
  btClose: () => ipcRenderer.invoke('bt-close'),
  btConnect: addr => ipcRenderer.invoke('bt-connect', addr),
  onBt: cb => ipcRenderer.on('bt-event', (_e, m) => cb(m)),
  onUi: cb => ipcRenderer.on('ui-changed', (_e, u) => cb(u)),
  checkUpdates: () => ipcRenderer.invoke('check-updates'),
  trayPanel: () => ipcRenderer.invoke('tray-panel'),
  screenInfo: () => ipcRenderer.invoke('screen-info'),
  startAgent: () => ipcRenderer.invoke('start-agent'),
  agentInfo: () => ipcRenderer.invoke('agent-info'),
  buildAgent: () => ipcRenderer.invoke('build-agent'),
  onBuild: cb => ipcRenderer.on('agent-build', (_e, m) => cb(m)),
  flowInfo: () => ipcRenderer.invoke('flow-info'),
  flowConfig: patch => ipcRenderer.invoke('flow-config', patch || null),
  flowSearch: on => ipcRenderer.invoke('flow-search', !!on),
  flowRemove: id => ipcRenderer.invoke('flow-remove', id),
  flowConnect: id => ipcRenderer.invoke('flow-connect', id),
  onFlowEvent: cb => ipcRenderer.on('flow-event', (_e, m) => cb(m)),
});
